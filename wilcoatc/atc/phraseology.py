    def holding_instruction(
        self, aircraft: Aircraft, fix: str, radial: float, direction: str,
        turns: str = "right", leg_minutes: int = 1, efc: str = "",
        altitude_ft: float = 0.0, transition_altitude: int = 0,
        fix_spoken: str = "",
    ) -> str:
        """A full holding clearance, in the order ICAO Doc 4444 prescribes."""
        spoken_fix = fix_name(fix, fix_spoken)
        parts = [
            aircraft.spoken(True),
            f"hold {direction} of {spoken_fix}",
            f"on the {self.hdg(radial)} radial",
        ]
        if altitude_ft:
            parts.append(f"maintain {self.alt(altitude_ft, transition_altitude)}")
        parts.append(f"{turns} turns")
        parts.append(f"{self.d(leg_minutes)} minute legs")
        if efc:
            parts.append(f"expect further clearance {efc}")
        return _join(*parts) + "."

    # ------------------------------------------------------------------
    # VFR: airspace, advisories and levels
    # ------------------------------------------------------------------
    #
    # A VFR flight is worked on a different set of words from an IFR one, and
    # using the IFR set is the commonest way a simulated controller gives
    # itself away. It is never "cleared to" anywhere, it is never told to
    # "climb and maintain", and the level it flies is its own business unless
    # something is above it -- so the phrases here are approvals, ceilings and
    # advisories rather than clearances.

    @property
    def vfr_squawk(self) -> str:
        """The conspicuity code, which is regional: 1200 in the US, 7000 in Europe."""
        return "1200" if self.dialect == "faa" else "7000"

    def squawk_vfr(self, aircraft: Aircraft) -> str:
        if self.dialect == "faa":
            return _join(aircraft.spoken(True), "squawk VFR") + "."
        return _join(aircraft.spoken(True),
                     f"squawk {sp.squawk(self.vfr_squawk, self.digit_dialect)}") + "."

    def maintain_vfr_clause(self, altitude_ft: float = 0.0, *,
                            at_or_below: bool = True,
                            transition_altitude: int = 0) -> str:
        """The clause on its own, for a template that carries it.

        "Radar contact, maintain VFR at or below three thousand" is one
        transmission, not two, so the words have to be available without the
        callsign in front of them.
        """
        if not altitude_ft:
            return "maintain VFR"
        limit = "at or below" if at_or_below else "at or above"
        return f"maintain VFR {limit} {self.alt(altitude_ft, transition_altitude)}"

    def maintain_vfr(self, aircraft: Aircraft, altitude_ft: float = 0.0, *,
                     at_or_below: bool = True, transition_altitude: int = 0,
                     abbreviated: bool = True) -> str:
        """``"maintain VFR at or below three thousand"``.

        The only altitude instruction a VFR flight normally gets. It is a
        ceiling or a floor, not a level to hold, because holding a level is
        what an IFR aircraft does.
        """
        return _join(aircraft.spoken(abbreviated), self.maintain_vfr_clause(
            altitude_ft, at_or_below=at_or_below,
            transition_altitude=transition_altitude)) + "."

    def vfr_altitude_discretion(self, aircraft: Aircraft) -> str:
        """What a radar controller says when a VFR pilot asks for a level."""
        return _join(aircraft.spoken(True), "maintain VFR",
                     "altitude your discretion") + "."

    def cleared_through_airspace(
        self, aircraft: Aircraft, airspace: str, *, altitude_ft: float = 0.0,
        route: str = "", report: str = "", transition_altitude: int = 0,
    ) -> str:
        """A transit of somebody's airspace, on the way past.

        FAA JO 7110.65 7-8-3 and 7-9-4: Class C and B need an explicit
        clearance through, Class D needs two-way contact and an approval. All
        three are the same shape -- through what, at what level, reporting what
        -- so one template covers them.
        """
        parts = [aircraft.spoken(True), f"cleared through the {airspace}"]
        if route:
            parts.append(route)
        if altitude_ft:
            parts.append(
                f"maintain VFR at or below {self.alt(altitude_ft, transition_altitude)}")
        else:
            parts.append("maintain VFR")
        if report:
            parts.append(f"report {report}")
        return _join(*parts) + "."

    def remain_clear_of_airspace(self, aircraft: Aircraft, airspace: str,
                                 station: str = "", *, reason: str = "") -> str:
        """The refusal, which is a real answer and has to be available.

        "Remain outside Class Charlie" is what a busy sector says, and a
        controller that can only ever approve a transit is not a controller.
        """
        parts = [self.addressed(aircraft, station),
                 f"remain clear of the {airspace}"]
        if reason:
            parts.append(reason)
        parts.append("standby")
        return _join(*parts) + "."

    def flight_following_approved(
        self, aircraft: Aircraft, station: str, squawk: str,
    ) -> str:
        """Radar advisories for a VFR flight, which start with a code.

        The code comes first, because the controller cannot identify the
        aircraft until it is squawking one; "radar contact" follows on the next
        transmission, once it can see it.
        """
        return _join(
            self.addressed(aircraft, station),
            f"squawk {sp.squawk(squawk, self.digit_dialect)}",
            "maintain VFR",
        ) + "."

    def flight_following_unavailable(self, aircraft: Aircraft) -> str:
        """Advisories are workload permitting, and sometimes the answer is no."""
        return _join(aircraft.spoken(True),
                     "unable flight following due to controller workload",
                     "remain VFR") + "."

    # ------------------------------------------------------------------
    # handoffs
    # ------------------------------------------------------------------

    def handoff(
        self, aircraft: Aircraft, next_station: str, next_freq: float,
        *, when: str = "", farewell: bool = False, welcome: str = "",
        abbreviated: bool = True,
    ) -> str:
        """Transfer of communication.

        FAA phrasing is "contact <facility> <frequency>" with no "on"; a
        good-day is common but never part of the instruction itself.

        ``welcome`` is the arrival version of that courtesy, and it names the
        place: a tower that has just watched you land says "welcome to
        Prague" rather than "have a good flight", which is what it says to
        somebody leaving.
        """
        parts = [self.addressed(aircraft, "", abbreviated)]
        if welcome:
            parts.append(f"welcome to {welcome}")
        body = f"contact {next_station} {self.freq(next_freq)}"
        if when:
            body = f"{when}, {body}"
        parts.append(body)
        text = _join(*parts) + "."
        # A welcome is the farewell for an arrival. Saying both would be
        # greeting somebody and taking leave of them in one breath.
        if farewell and not welcome:
            text += " " + _pick(
                ("Good day.", "So long.", "Have a good flight."),
                aircraft.callsign.written + next_station,
            )
        return text

