"""Controller phraseology.

Every word a controller says in this system is produced here, from a fixed
template. Nothing is generated by a language model. That is a deliberate
architectural choice: a model asked to "sound like ATC" will drift, invent
instructions that do not exist, and phrase the same clearance differently every
time. Templates cannot. The cost is that only the instructions written here can
ever be issued; the benefit is that every instruction issued is correct, and a
pilot who reads back what they heard is reading back real phraseology.

Sources followed:

  * FAA JO 7110.65   -- Air Traffic Control (US phraseology, ``faa`` dialect)
  * FAA AIM ch. 4-2  -- Radio communications phraseology and technique
  * ICAO Doc 4444    -- PANS-ATM ch. 12, radiotelephony phraseology
  * ICAO Doc 9432    -- Manual of Radiotelephony

Where the two dialects differ the template branches: the FAA says "climb and
maintain one two thousand" and "altimeter two niner niner two", ICAO says
"climb to flight level one two zero" and "QNH one zero one three".

Controlled variety comes from :func:`_pick`, which chooses between phrasings
that are *all* correct, keyed on a stable hash so the same situation always
produces the same words.
"""

from __future__ import annotations

import hashlib
from dataclasses import dataclass, field
from typing import Sequence

from . import speech as sp
from ..navdata.channels import spoken_channel

Dialect = sp.Dialect


def _pick(options: Sequence[str], key: str) -> str:
    """Deterministically choose one of several equally correct phrasings."""
    if len(options) == 1:
        return options[0]
    h = int.from_bytes(hashlib.sha256(key.encode("utf-8")).digest()[:4], "big")
    return options[h % len(options)]


def language_of(phraseology) -> str:
    """Which language a phraseology speaks.

    The dialect and the language are not the same question -- English at Orly
    is ICAO English, not US English -- so a phraseology states its language
    outright rather than having it inferred from the dialect. Everything that
    addresses an aircraft has to ask, because a callsign is spoken differently
    in each language.
    """
    return getattr(phraseology, "language", "") or "en"


def _is_letters(name: str) -> bool:
    """A point named by one to three capitals, like N, SE or NG."""
    return 1 <= len(name) <= 3 and name.isalpha() and name.isupper()


def _join_words(*words: str) -> str:
    """Words into one clause, dropping the empty ones."""
    return " ".join(w.strip() for w in words if w and w.strip())


def _join(*parts: str) -> str:
    """Join clause fragments, dropping empties and tidying punctuation."""
    text = ", ".join(p.strip().strip(",") for p in parts if p and p.strip().strip(","))
    return text.replace(" ,", ",").replace(",,", ",").strip(" ,")


def _sentence(text: str) -> str:
    """One full stop at the end, however many the parts arrived with."""
    text = (text or "").rstrip()
    return text if text.endswith((".", "!", "?")) else text + "."


def without_callsign(text: str, aircraft) -> str:
    """An instruction with the callsign it opens with taken off the front.

    Every instruction a controller gives begins by naming the aeroplane, which
    is right, and which makes repeating one awkward: the repeat has to name
    the aeroplane too, and then the instruction names it again.

        November two sierra papa, I say again. November two sierra papa,
        contact de Gaulle Ground one two one decimal six one zero.

    Nobody says that. The callsign is said once, the announcement follows it,
    and then the instruction carries on from where the announcement left off.
    Which form the instruction used -- the full callsign or the abbreviated
    one, in whichever language it was said in -- is not knowable from here, so
    every form the aeroplane answers to is tried, longest first.
    """
    body = (text or "").lstrip()
    if aircraft is None or not body:
        return body

    forms = {aircraft.spoken(False), aircraft.spoken(True)}
    for callsign in [aircraft.callsign, *aircraft.callsigns.values()]:
        for form in (callsign.spoken_full, callsign.spoken_short):
            if not form:
                continue
            forms.add(form)
            if aircraft.wake:
                forms.add(f"{form} {aircraft.wake}")
    for form in sorted((f for f in forms if f), key=len, reverse=True):
        if body.lower().startswith(form.lower()):
            return body[len(form):].lstrip().lstrip(",").lstrip()
    return body


