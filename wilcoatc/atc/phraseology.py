# ICAO wake categories that are spoken as part of the callsign. A 747 is
# "heavy" on every transmission; an A380 is "super". Getting this wrong is
# immediately obvious to an airline pilot.
SUPER_TYPES = {"A388", "A124", "A225"}
HEAVY_TYPES = {
    "A332", "A333", "A337", "A338", "A339", "A342", "A343", "A345", "A346",
    "A359", "A35K", "A3ST", "B742", "B743", "B744", "B748", "B74S", "B762",
    "B763", "B764", "B772", "B773", "B77L", "B77W", "B778", "B779", "B788",
    "B789", "B78X", "MD11", "DC10", "IL96", "A306", "A310", "C5M", "C17",
    "K35R", "B52", "AN22", "IL76",
}


def wake_suffix(aircraft_type: str) -> str:
    """``"heavy"``, ``"super"`` or empty, appended to the spoken callsign."""
    code = (aircraft_type or "").strip().upper()
    if code in SUPER_TYPES:
        return "super"
    if code in HEAVY_TYPES:
        return "heavy"
    return ""


def fix_name(ident: str, spoken: str = "") -> str:
    """How a waypoint or navaid is said on the radio.

    Five-letter RNAV fixes are deliberately coined to be pronounceable and are
    spoken as words -- CAMRN is "cam-run", never "Charlie Alpha Mike Romeo
    November". Two- and three-letter navaid identifiers are spelled out when
    all we have is the identifier; pass ``spoken`` with the navaid's published
    name ("Robbinsville") whenever it is known, because that is what a
    controller actually says.
    """
    ident = (ident or "").strip().upper()
    if spoken:
        return spoken
    if not ident:
        return ""
    if len(ident) <= 3 or not ident.isalpha():
        return sp.letters(ident)
    # Title case gives the synthesiser its best chance at a natural reading
    # rather than spelling the letters out.
    return ident.capitalize()


