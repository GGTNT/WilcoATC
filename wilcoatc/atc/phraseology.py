@dataclass
class Aircraft:
    """What the controller knows about the aircraft it is talking to.

    A callsign is spoken differently in different languages: ``AFR1234`` is
    "Airfrans twelve thirty four" to an English-speaking controller and "Air
    France mille deux cent trente-quatre" to a French one. Both forms are held
    here, and ``language`` selects between them, so the phraseology templates
    can stay ignorant of the question.
    """

    callsign: sp.Callsign
    type_code: str = ""
    wake: str = ""                 # "", "heavy", "super"
    is_heavy: bool = False
    # Alternative spoken forms, keyed by language code.
    callsigns: dict[str, sp.Callsign] = field(default_factory=dict)
    language: str = "en"

    def for_language(self, language: str) -> sp.Callsign:
        return self.callsigns.get((language or "en")[:2], self.callsign)

    def spoken(self, abbreviated: bool = False) -> str:
        base = self.for_language(self.language).spoken(abbreviated)
        return f"{base} {self.wake}".strip() if self.wake else base

    def variants(self) -> list[str]:
        """Every spoken and written form, for matching what the pilot said."""
        found = {self.callsign.written}
        for callsign in [self.callsign, *self.callsigns.values()]:
            found.add(callsign.spoken_full)
            found.add(callsign.spoken_short)
        return [v for v in found if v]


@dataclass
class Weather:
    wind_dir: float = 0.0
    wind_kt: float = 0.0
    gust_kt: float = 0.0
    visibility_sm: float = 10.0
    altimeter_inhg: float = 29.92
    qnh_hpa: float = 1013.0
    temperature_c: float = 15.0
    dewpoint_c: float = 10.0
    clouds: list[tuple[str, int]] = field(default_factory=list)  # [("FEW", 4500)]
    remarks: str = ""
    raw: str = ""
    # Magnetic variation at the field, east positive. ``wind_dir`` stays true,
    # as observed and as the runway headings in the data are; a spoken wind
    # subtracts this (see :func:`spoken_wind_direction`).
    variation: float = 0.0
    # A METAR "VRB": no direction at all, which is not a wind from the north.
    variable: bool = False
    # Where the wind and pressure were read from, for the decision log:
    # "metar KBOS", "nearest KLGA", "sim+metar KBOS", "sim", "default".
    source: str = ""


def spoken_wind_direction(weather: Weather) -> float | str:
    """The direction a controller reads out: magnetic, in tens, or "VRB".

    Observations are true and every wind a controller or an ATIS speaks is
    magnetic (ICAO Doc 4444 6.6; FAA JO 7110.65 2-6-4), rounded to ten
    degrees as both read it. A field with no variation known reads the
    observation as it is.
    """
    if weather.variable:
        return "VRB"
    magnetic = (float(weather.wind_dir) - float(weather.variation or 0.0)) % 360.0
    tens = int(round(magnetic / 10.0)) * 10 % 360
    return float(tens or 360) if weather.wind_kt >= 0.5 else 0.0


class Phraseology:
    """Builds controller transmissions for one dialect."""

    # The dialect varies; the language does not. This is the English class.
    language = "en"

    def __init__(self, dialect: Dialect = "faa", strict_icao_digits: bool = False,
                 transition: int = 18000):
        """``dialect`` selects the phrasing; ``strict_icao_digits`` the numbers.

        ICAO Annex 10 prescribes "tree", "fower" and "fife" alongside "niner",
        and UK CAP 413 repeats them. In practice only "niner" is universal,
        with "fife" fairly common and "tree"/"fower" rare outside training.
        Reading every number the strict way sounds theatrical to a line pilot,
        so the default keeps ICAO *phrasing* (decimal, QNH, "climb to") with
        ordinary digit words. Set this flag for the by-the-book reading.

        ``transition`` is where altitudes become flight levels in this
        region. It belongs to the object rather than to each call because
        forgetting it is silent and wrong in the same direction every time:
        every caller that left it out got eighteen thousand feet, which is
        correct in the Americas and nowhere else, so an aircraft over London
        reported "one eight thousand" for a level everyone on the frequency
        calls flight level one eight zero. A caller with a better answer --
        the controller, who knows which airport the instruction is for --
        still passes one.
        """
        self.dialect = dialect
        self.strict_icao_digits = strict_icao_digits
        self.transition = int(transition) or 18000
        # Only the digit table differs; everything else follows ``dialect``.
        self.digit_dialect: Dialect = (
            "icao" if (dialect == "icao" and strict_icao_digits) else "faa"
        )

    # ------------------------------------------------------------------
    # primitives
    # ------------------------------------------------------------------

    def d(self, value) -> str:
        return sp.digits(value, self.digit_dialect)

    def alt(self, feet: float, transition: int = 0, level_from: int = 0) -> str:
        return sp.altitude(feet, self.digit_dialect,
                           transition or self.transition, level_from)

    def freq(self, mhz: float) -> str:
        # The separator word follows the region; the digits follow the style.
        text = sp.frequency(mhz, self.digit_dialect)
        if self.dialect == "icao":
            text = text.replace(" point ", " decimal ")
        return text

    def hdg(self, degrees: float) -> str:
        return sp.heading(degrees, self.digit_dialect)

    def rwy(self, ident: str) -> str:
        # The leading zero is regional; the digit words are a style choice.
        return sp.runway(ident, self.dialect, self.digit_dialect)

    def addressed(self, aircraft: Aircraft, station: str = "",
                  abbreviated: bool = False) -> str:
        """Open a transmission: aircraft first, then who is calling."""
        who = aircraft.spoken(abbreviated)
        return _join(who, station) if station else who

    # ------------------------------------------------------------------
    # clearance delivery
    # ------------------------------------------------------------------

    def ifr_clearance(
        self,
        aircraft: Aircraft,
        station: str,
        destination: str,
        *,
        departure_procedure: str = "",
        transition: str = "",
        route: str = "as filed",
        initial_altitude: float = 5000,
        cruise_altitude: float = 0,
        expect_minutes: int = 10,
        departure_freq: float = 0.0,
        squawk: str = "1200",
        transition_altitude: int = 0,
    ) -> str:
        """A full IFR clearance in CRAFT order.

        Clearance limit, Route, Altitude, Frequency, Transponder -- the order
        every instrument pilot is taught to write it down in, and the order
        controllers actually read it.
        """
        # --- clearance limit and route ---
        if departure_procedure:
            via = f"via the {departure_procedure} departure"
            if transition:
                via += f", {transition} transition"
            via += f", then {route}"
        else:
            via = f"via {route}"

        cleared_to = f"cleared to the {destination} airport {via}"
        if self.dialect == "icao":
            cleared_to = f"cleared to {destination} {via}"

        # --- altitude ---
        if self.dialect == "faa":
            climb = f"maintain {self.alt(initial_altitude, transition_altitude)}"
            if cruise_altitude and cruise_altitude > initial_altitude:
                climb += (
                    f", expect {self.alt(cruise_altitude, transition_altitude)} "
                    f"{self.d(expect_minutes)} minutes after departure"
                )
        else:
            climb = f"climb to {self.alt(initial_altitude, transition_altitude)}"
            if cruise_altitude and cruise_altitude > initial_altitude:
                climb += (
                    f", expect {self.alt(cruise_altitude, transition_altitude)} "
                    f"{self.d(expect_minutes)} minutes after departure"
                )

        parts = [self.addressed(aircraft, station), cleared_to, climb]

        if departure_freq:
            label = "departure frequency" if self.dialect == "faa" else "departure frequency"
            parts.append(f"{label} {self.freq(departure_freq)}")
        parts.append(f"squawk {sp.squawk(squawk, self.digit_dialect)}")
        return _join(*parts) + "."

    def vfr_departure_clearance(
        self,
        aircraft: Aircraft,
        station: str,
        *,
        airspace: str = "",
        departure_freq: float = 0.0,
        squawk: str = "1200",
        altitude_restriction: float = 0.0,
        direction: str = "",
    ) -> str:
        """VFR release out of controlled airspace.

        A VFR flight is not cleared anywhere. It is released in a direction,
        held at or below a level where something is above it, given a code and
        sent on its way -- so this says "departure approved" and "maintain
        VFR", never "cleared to" and never a level to maintain.
        """
        parts = [self.addressed(aircraft, station)]
        if airspace:
            body = f"cleared out of the {airspace}"
            if direction:
                body += f", {direction} departure approved"
            parts.append(body)
        elif direction:
            parts.append(f"{direction} departure approved")
        else:
            parts.append("VFR departure approved")
        if altitude_restriction:
            parts.append(f"maintain VFR at or below {self.alt(altitude_restriction)}")
        else:
            parts.append("maintain VFR")
        if departure_freq:
            parts.append(f"departure frequency {self.freq(departure_freq)}")
        parts.append(f"squawk {sp.squawk(squawk, self.digit_dialect)}")
        return _join(*parts) + "."

    def readback_correct(
        self, aircraft: Aircraft, *, next_station: str = "", next_freq: float = 0.0,
        when: str = "when ready to taxi",
    ) -> str:
        parts = [aircraft.spoken(True), "readback correct"]
        if next_station and next_freq:
            parts.append(f"contact {next_station} {self.freq(next_freq)} {when}")
        elif next_station:
            parts.append(f"contact {next_station} {when}")
        return _join(*parts) + "."

    def readback_incorrect(self, aircraft: Aircraft, correction: str) -> str:
        """Correct one item without re-reading the whole clearance."""
        return _join(aircraft.spoken(True), "negative", correction) + "."

    # What a controller says to a pilot who has not read back. FAA JO 7110.65
    # 4-3-2 and 2-4-3 make the readback of a hold-short instruction mandatory
    # and name it explicitly -- "read back hold short instructions" -- which is
    # why the wording changes with what is owed rather than being one phrase.
    READBACK_ITEM_NAMES: dict[str, str] = {
        "hold_short": "hold short instructions",
        "runway": "the runway assignment",
        "altitude_ft": "the altitude",
        "heading": "the heading",
        "squawk": "the transponder code",
        "frequency": "the frequency",
        "speed_kt": "the speed",
    }

    def read_back_instruction(self, aircraft: Aircraft,
                              items: Sequence[str] = ()) -> str:
        """Ask for a readback that was not given.

        Named item by item where the controller would name it. "Read back hold
        short instructions" is the phrase in the book, and it is the one case
        where a controller is required to insist rather than let it go.
        """
        if "hold_short" in items:
            body = "read back hold short instructions"
        elif len(items) == 1:
            body = f"read back {self.READBACK_ITEM_NAMES.get(items[0], 'all instructions')}"
        else:
            body = "read back all instructions"
        return _join(aircraft.spoken(True), body) + "."

    def say_again_instruction(self, aircraft: Aircraft, text: str) -> str:
        """Re-read an instruction in full, for a pilot who plainly missed it.

        The announcement goes between the callsign and the instruction, and
        the instruction's own copy of the callsign comes off -- otherwise the
        aeroplane is named twice in a row, which is what this used to do.
        """
        return _sentence(_join(aircraft.spoken(True), "I say again",
                               without_callsign(text, aircraft)))

    # ------------------------------------------------------------------
    # ground
    # ------------------------------------------------------------------

    def taxi_to_runway(
        self,
        aircraft: Aircraft,
        station: str,
        runway: str,
        route: Sequence[str],
        *,
        hold_short: str = "",
        altimeter: float = 0.0,
        abbreviated: bool = True,
    ) -> str:
        """Taxi instruction.

        FAA JO 7110.65 10-3-1 requires the departure runway to be stated first,
        then the route, and a hold-short instruction for every runway crossed
        that is not explicitly cleared. The runway assignment is not a takeoff
        clearance and never implies one.
        """
        parts = [self.addressed(aircraft, station, abbreviated)]
        parts.append(f"runway {self.rwy(runway)}")
        if route:
            parts.append(f"taxi via {sp.taxi_route(route)}")
        else:
            parts.append("taxi to the runway")
        if hold_short:
            parts.append(f"hold short of runway {self.rwy(hold_short)}")
        if altimeter:
            parts.append(self.pressure(altimeter))
        return _join(*parts) + "."

    def taxi_to_parking(
        self, aircraft: Aircraft, station: str, route: Sequence[str],
        destination: str = "the ramp", *, hold_short: str = "",
        abbreviated: bool = True,
    ) -> str:
        parts = [self.addressed(aircraft, station, abbreviated)]
        if route:
            parts.append(f"taxi to {destination} via {sp.taxi_route(route)}")
        else:
            parts.append(f"taxi to {destination}")
        if hold_short:
            parts.append(f"hold short of runway {self.rwy(hold_short)}")
        return _join(*parts) + "."

    def cross_runway(
        self, aircraft: Aircraft, runway: str, *, then: str = "", abbreviated: bool = True
    ) -> str:
        parts = [aircraft.spoken(abbreviated), f"cross runway {self.rwy(runway)}"]
        if then:
            parts.append(then)
        return _join(*parts) + "."

    def hold_short_instruction(self, aircraft: Aircraft, runway: str) -> str:
        return _join(aircraft.spoken(True),
                     f"hold short of runway {self.rwy(runway)}") + "."

    def hold_position(self, aircraft: Aircraft) -> str:
        word = "hold position" if self.dialect == "faa" else "hold position"
        return _join(aircraft.spoken(True), word) + "."

    def continue_taxi(self, aircraft: Aircraft, route: Sequence[str] = ()) -> str:
        if route:
            return _join(aircraft.spoken(True),
                         f"continue taxi via {sp.taxi_route(route)}") + "."
        return _join(aircraft.spoken(True), "continue taxi") + "."

    def give_way(self, aircraft: Aircraft, traffic: str) -> str:
        return _join(aircraft.spoken(True), f"give way to {traffic}",
                     "then continue taxi") + "."

    # ------------------------------------------------------------------
    # tower
    # ------------------------------------------------------------------

    def line_up_and_wait(
        self, aircraft: Aircraft, runway: str, *, reason: str = "",
        station: str = "", abbreviated: bool = True,
    ) -> str:
        """"Line up and wait" replaced "position and hold" in the US in 2010."""
        parts = [self.addressed(aircraft, station, abbreviated),
                 f"runway {self.rwy(runway)}", "line up and wait"]
        if reason:
            parts.append(reason)
        return _join(*parts) + "."

    def cleared_for_takeoff(
        self,
        aircraft: Aircraft,
        runway: str,
        weather: Weather | None = None,
        *,
        station: str = "",
        after_departure: str = "",
        abbreviated: bool = True,
        traffic: str = "",
    ) -> str:
        parts = [self.addressed(aircraft, station, abbreviated)]
        if traffic:
            parts.append(traffic)
        if weather is not None:
            parts.append(self.wind(weather))
        parts.append(f"runway {self.rwy(runway)}")
        if after_departure:
            parts.append(after_departure)
        parts.append("cleared for takeoff")
        return _join(*parts) + "."

    def cleared_to_land(
        self,
        aircraft: Aircraft,
        runway: str,
        weather: Weather | None = None,
        *,
        station: str = "",
        sequence: str = "",
        abbreviated: bool = True,
    ) -> str:
        parts = [self.addressed(aircraft, station, abbreviated)]
        if sequence:
            parts.append(sequence)
        if weather is not None:
            parts.append(self.wind(weather))
        parts.append(f"runway {self.rwy(runway)}")
        parts.append("cleared to land")
        return _join(*parts) + "."

    def cleared_touch_and_go(self, aircraft: Aircraft, runway: str,
                             weather: Weather | None = None, *,
                             sequence: str = "", station: str = "",
                             abbreviated: bool = True) -> str:
        """"Cleared for the option" leaves the choice to the pilot.

        FAA JO 7110.65 3-10-6: it authorises a touch-and-go, a low approach, a
        missed approach, a stop-and-go or a full stop, and it is what a tower
        issues to an aircraft doing circuits rather than reissuing a landing
        clearance every time round.
        """
        parts = [self.addressed(aircraft, station, abbreviated)]
        if sequence:
            parts.append(sequence)
        if weather is not None:
            parts.append(self.wind(weather))
        parts += [f"runway {self.rwy(runway)}", "cleared for the option"]
        return _join(*parts) + "."

    def closed_traffic_approved(
        self, aircraft: Aircraft, runway: str, direction: str = "left",
        weather: Weather | None = None, *, station: str = "",
        abbreviated: bool = True,
    ) -> str:
        """Takeoff clearance for an aircraft staying in the circuit."""
        parts = [self.addressed(aircraft, station, abbreviated)]
        if weather is not None:
            parts.append(self.wind(weather))
        parts += [f"runway {self.rwy(runway)}", "cleared for takeoff",
                  f"{direction} closed traffic approved"]
        return _join(*parts) + "."

    def make_short_approach(self, aircraft: Aircraft, reason: str = "") -> str:
        parts = [aircraft.spoken(True), "make short approach"]
        if reason:
            parts.append(reason)
        return _join(*parts) + "."

    def turn_out_approved(self, aircraft: Aircraft, direction: str = "") -> str:
        """What a VFR departure is given instead of "fly runway heading"."""
        if direction:
            return _join(aircraft.spoken(True),
                         f"{direction} turn out approved") + "."
        return _join(aircraft.spoken(True), "on course approved") + "."

    def go_around(self, aircraft: Aircraft, reason: str = "",
                  instruction: str = "") -> str:
        parts = [aircraft.spoken(True), "go around"]
        if reason:
            parts.append(reason)
        if instruction:
            parts.append(instruction)
        return _join(*parts) + "."

    def continue_approach(self, aircraft: Aircraft, reason: str = "") -> str:
        parts = [aircraft.spoken(True), "continue approach"]
        if reason:
            parts.append(reason)
        return _join(*parts) + "."

    def sequence_number(self, position: int, traffic: str = "") -> str:
        """``"number two, follow the Boeing seven three seven on short final"``."""
        words = {1: "one", 2: "two", 3: "three", 4: "four", 5: "five",
                 6: "six", 7: "seven", 8: "eight"}
        text = f"number {words.get(position, self.d(position))}"
        if traffic:
            text += f", follow {traffic}"
        return text

    def enter_pattern(
        self, aircraft: Aircraft, station: str, runway: str, leg: str = "downwind",
        direction: str = "left", *, report: str = "", weather: Weather | None = None,
        sequence: str = "", straight_in: bool = False,
    ) -> str:
        """Join instruction for a VFR arrival.

        FAA JO 7110.65 3-10-2: the leg to enter, the runway, and a reporting
        point. "Make left traffic" is the phrase when the aircraft is joining
        the circuit at whichever leg suits it; naming the leg -- "enter left
        downwind" -- is what a tower says when it wants a particular one, and
        is the commoner instruction, so the leg is said unless it is empty.
        """
        parts = [self.addressed(aircraft, station)]
        if sequence:
            parts.append(sequence)
        if straight_in:
            parts.append(f"make straight-in runway {self.rwy(runway)}")
        elif leg:
            parts.append(f"enter {direction} {leg} runway {self.rwy(runway)}")
        else:
            parts.append(f"make {direction} traffic runway {self.rwy(runway)}")
        if report:
            parts.append(f"report {report}")
        if weather is not None:
            parts.append(self.wind(weather))
            parts.append(self.pressure(
                weather.altimeter_inhg if self.dialect == "faa" else weather.qnh_hpa
            ))
        return _join(*parts) + "."

    def report_position(self, aircraft: Aircraft, point: str) -> str:
        """``"report midfield downwind"``, ``"report a two mile final"``.

        The reporting point is what a tower uses instead of radar to sequence
        a circuit, so it is an instruction in its own right rather than a
        clause hanging off another one.
        """
        return _join(aircraft.spoken(True), f"report {point}") + "."

    def extend_downwind(self, aircraft: Aircraft, reason: str = "") -> str:
        parts = [aircraft.spoken(True), "extend downwind"]
        if reason:
            parts.append(reason)
        parts.append("I'll call your base")
        return _join(*parts) + "."

    def cleared_low_approach(self, aircraft: Aircraft, runway: str) -> str:
        return _join(aircraft.spoken(True), f"runway {self.rwy(runway)}",
                     "cleared low approach") + "."

    def wind_check(self, weather: Weather, aircraft: Aircraft | None = None) -> str:
        parts = []
        if aircraft:
            parts.append(aircraft.spoken(True))
        parts.append(self.wind(weather))
        return _join(*parts) + "."

