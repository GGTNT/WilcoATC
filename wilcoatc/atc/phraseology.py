    def squawk(self, aircraft: Aircraft, code: str) -> str:
        return _join(aircraft.spoken(True),
                     f"squawk {sp.squawk(code, self.digit_dialect)}") + "."

    def ident(self, aircraft: Aircraft) -> str:
        return _join(aircraft.spoken(True), "ident") + "."

    def pressure(self, value: float) -> str:
        """Altimeter setting in the units the region uses.

        The *format* follows the region -- four digits of inches with no
        decimal point in the US, four digits of hectopascals elsewhere -- while
        the digit words follow the configured style.
        """
        if self.dialect == "faa":
            return f"altimeter {self.d(f'{float(value):.2f}'.replace('.', ''))}"
        # Three figures below a thousand: "QNH niner niner zero", never with
        # a zero in front of it.
        return f"QNH {self.d(str(int(round(float(value)))))}"

    def wind(self, weather: Weather) -> str:
        direction = spoken_wind_direction(weather)
        if (direction == "VRB" and self.dialect == "icao"
                and int(round(weather.wind_kt)) > 0):
            # ICAO reads a variable wind with its unit, "wind variable five
            # knots"; the FAA form, "wind variable at five" (JO 7110.65
            # 2-6-4), is what sp.wind already says.
            text = f"wind variable {self.d(int(round(weather.wind_kt)))} knots"
            if weather.gust_kt and weather.gust_kt > weather.wind_kt:
                text += f" gusting {self.d(int(round(weather.gust_kt)))}"
            return text
        return sp.wind(direction, weather.wind_kt,
                       weather.gust_kt or None, self.digit_dialect)

    def altimeter_setting(self, aircraft: Aircraft, value: float) -> str:
        return _join(aircraft.spoken(True), self.pressure(value)) + "."

    def say_again(self, aircraft: Aircraft | None = None, item: str = "") -> str:
        if item:
            body = f"say again your {item}"
        else:
            body = _pick(("say again", "say again, you were unreadable"),
                         item or "x")
        if aircraft:
            return _join(aircraft.spoken(True), body) + "."
        return body.capitalize() + "."

    def expecting(self, aircraft: Aircraft, calls: Sequence[str] = ()) -> str:
        """Name the call the controller is waiting for.

        "Say again" tells a pilot that they were not understood and nothing
        else, which on a frequency they have never worked before is no help at
        all. Naming the call is: the controller knows what would make sense
        here, and there is no reason to keep it to itself.
        """
        wanted = [call for call in calls if call]
        if not wanted:
            return self.say_again(aircraft)
        if len(wanted) == 1:
            body = f"expecting {wanted[0]}"
        else:
            body = "expecting " + ", or ".join(wanted)
        return _join(aircraft.spoken(True), body) + "."

    def roger(self, aircraft: Aircraft) -> str:
        return _join(aircraft.spoken(True),
                     _pick(("roger", "roger that"), aircraft.callsign.written)) + "."

    def roger_runway(self, aircraft: Aircraft, runway: str) -> str:
        """Acknowledge a runway the pilot asked for, by naming it back.

        A bare "roger" to "request runway three zero" is indistinguishable
        from not having heard it, which is the whole of what was wrong: the
        pilot asks again, gets another roger, and taxis to the other runway.
        """
        return _join(aircraft.spoken(True), "roger",
                     f"expect runway {self.rwy(runway)}") + "."

