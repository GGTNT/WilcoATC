# -*- coding: utf-8 -*-
"""Who works the cruise: en-route sectors, by airspace rather than by range.

A flight from Singapore to Hong Kong heard "contact Singapore Control" and
then nothing for two and a half hours. En-route control was modelled by
range: a centre frequency was a row filed at one aerodrome and counted as
reachable within three hundred miles of it. Five hundred miles from
Singapore nobody was on Singapore Control's number, the engine kept the old
station alive by a patch, and the next FIR had no frequency in the shipped
data, so the centre had nobody to hand the flight to. The boundaries were
loaded and drew the map; they did not decide who was working the flight.

Here a :class:`Sector` is a volume of airspace with a callsign and its
frequencies, and the one the aeroplane is in is its controller wherever in
it the aeroplane is. Sectors come from, in order of precedence:

1. the pilot's own ``sectors.csv`` beside the database (format in its
   header), for a sector nothing else has right;
2. the VatGlasses sectors, when the pilot has installed them (an opt-in
   download under CC BY-NC-SA, never bundled): real sector splits with
   levels and frequencies;
3. the FIR outlines (``Boundaries.geojson``), named from ``VATSpy.dat``,
   with a frequency from ``fir_frequencies.csv`` (shipped, each row with
   its AIP source; a row may give levels, which is how an upper area
   control centre is put above a FIR), else a centre frequency filed at an
   airfield that names the FIR, the one filed nearest where it is asked
   about, else one **invented** -- stable for the FIR, and logged as
   invented every session it is used. Silence was the alternative, and a
   pilot cannot tell silence from a program that has stopped.

FAA NASR ARTCC sector frequencies would sit between 2 and 3 for the United
States; they are not in the tree yet, and the US is covered by the centre
rows OurAirports files at its fields.

A sector over the ocean with no radar is ``OCEANIC``: worked on HF, which
no simulator COM radio tunes, so its station is held by the engine rather
than by COM1 (see ``Engine._go_oceanic``).
"""

from __future__ import annotations

import csv
import hashlib
import logging
from dataclasses import dataclass
from pathlib import Path

from ..logs import decision
from ..navdata.build import bearing_deg, haversine_nm, project
from ..navdata.channels import same_channel
from ..navdata.db import NavDB, Station, _point_in_ring, dialect_for

log = logging.getLogger(__name__)

RADAR = "radar"
OCEANIC = "oceanic"
FIS = "fis"

FIR_FREQUENCIES = "fir_frequencies.csv"
PILOT_SECTORS = "sectors.csv"
# The US ARTCCs and their remote sites, generated by scripts/build_nasr.py
# from FAA NASR (ARB_SEG, FRQ): the pilot's sectors.csv format, and where
# each frequency is transmitted from.
FAA_SECTORS = "sectors_faa.csv"
FAA_SITES = "centre_sites_faa.csv"
# An ARTCC's ultra-high sectors start here. UNVERIFIED: FL350 is the usual
# floor of the ultra-high strata; NASR gives no figure.
ULTRA_HIGH_FT = 35000.0

# A station's description says where it came from; this prefix is what marks
# an oceanic one for everything that has only the Station in hand.
OCEANIC_MARK = "oceanic"

NO_CEILING_FT = 99900.0


@dataclass(frozen=True)
class Sector:
    """One controller's airspace, as the flight sees it."""

    id: str                          # FIR or sector id: "WSJC", "lf/RE"
    ident: str                       # what the station carries: the FIR code
    facility: str                    # "Singapore", or a full "Maastricht Radar"
    frequencies: tuple[float, ...]   # first is the one a handoff gives
    kind: str = RADAR
    source: str = "fir"              # pilot | vatglasses | faa | fir
    frequency_source: str = ""       # where the first frequency came from
    floor_ft: float = 0.0
    ceiling_ft: float = NO_CEILING_FT
    hf_khz: tuple[int, ...] = ()
    invented: bool = False

    @property
    def key(self) -> tuple[str, str, str]:
        """Two looks at the same airspace give the same key."""
        return (self.source, self.id, self.facility)

    @property
    def mhz(self) -> float:
        return self.frequencies[0] if self.frequencies else 0.0

    @property
    def oceanic(self) -> bool:
        return self.kind == OCEANIC

    def station(self, mhz: float = 0.0) -> Station:
        """The controller, as the rest of the program talks to one.

        On ``mhz`` when it is one of the sector's: the pilot tuned to it is
        talking to this controller on that frequency, and a station that
        took the first instead changed its key as the first did -- which,
        for an ARTCC giving its nearest site's, is every few minutes.

        The ident is the FIR's, not the field a borrowed frequency is filed
        at: two fields filing one centre on one number (Minnipa and Wudinna,
        Melbourne on 125.9) are one station, which is what let the engine
        drop the patch that kept the old station alive across a retune.
        """
        tag = OCEANIC_MARK if self.oceanic else "sector"
        on = next((f for f in self.frequencies
                   if mhz and same_channel(mhz, f, 4)), self.mhz)
        return Station(ident=self.ident, position="CTR", mhz=on,
                       facility=self.facility,
                       description=f"{tag} {self.id} ({self.source}"
                                   f"{', invented' if self.invented else ''})",
                       dialect=dialect_for(self.ident))

    def answers(self, mhz: float, tolerance_khz: int = 4) -> bool:
        return any(same_channel(mhz, f, tolerance_khz) for f in self.frequencies)


@dataclass(frozen=True)
class Crossing:
    """The next sector along the track, and how far off its boundary is."""

    sector: Sector
    distance_nm: float
    minutes: float
    lat: float
    lon: float


def is_oceanic(station: Station | None) -> bool:
    return station is not None and (station.description or "").startswith(
        OCEANIC_MARK)


def is_invented(station: Station | None) -> bool:
    """Whether a station's frequency was made up for want of a published one."""
    return station is not None and (station.description or "").endswith(
        ", invented)")


