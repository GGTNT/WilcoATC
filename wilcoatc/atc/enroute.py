@dataclass(frozen=True)
class FrequencyRow:
    fir: str
    callsign: str
    mhz: float
    floor_ft: float
    ceiling_ft: float
    kind: str
    source: str


@dataclass(frozen=True)
class PilotSector:
    id: str
    callsign: str
    frequencies: tuple[float, ...]
    floor_ft: float
    ceiling_ft: float
    kind: str
    rings: tuple
    box: tuple[float, float, float, float]
    source: str


def _rows(path: Path) -> list[dict]:
    """A CSV's data rows, past its ``#`` comment header."""
    if not path.exists():
        return []
    with path.open(encoding="utf-8", newline="") as fh:
        lines = [ln for ln in fh if ln.strip() and not ln.lstrip().startswith("#")]
    return list(csv.DictReader(lines))


def _level_ft(text: str, default: float) -> float:
    text = (text or "").strip()
    if not text:
        return default
    return float(text) * 100.0


def load_frequencies(path: Path) -> dict[str, list[FrequencyRow]]:
    out: dict[str, list[FrequencyRow]] = {}
    for row in _rows(path):
        try:
            mhz = float(row.get("mhz") or 0)
            entry = FrequencyRow(
                fir=(row.get("fir") or "").strip().upper(),
                callsign=(row.get("callsign") or "").strip(),
                mhz=mhz,
                floor_ft=_level_ft(row.get("floor_fl"), 0.0),
                ceiling_ft=_level_ft(row.get("ceiling_fl"), NO_CEILING_FT),
                kind=(row.get("kind") or RADAR).strip().lower(),
                source=(row.get("source") or "").strip())
        except ValueError:
            log.warning("%s: unreadable row %s", path.name, row)
            continue
        if entry.fir and entry.mhz:
            out.setdefault(entry.fir, []).append(entry)
    return out


def load_pilot_sectors(path: Path) -> list[PilotSector]:
    out = []
    for row in _rows(path):
        try:
            points = [tuple(float(v) for v in pair.split())
                      for pair in (row.get("points") or "").split(";")
                      if pair.strip()]
            mhz = tuple(float(v) for v in (row.get("mhz") or "").split())
        except ValueError:
            log.warning("%s: unreadable row %s", path.name, row)
            continue
        if len(points) < 3 or not mhz:
            log.warning("%s: %s needs three points and a frequency",
                        path.name, row.get("id"))
            continue
        ring = [[lon, lat] for lat, lon in points]
        lats = [p[0] for p in points]
        lons = [p[1] for p in points]
        out.append(PilotSector(
            id=(row.get("id") or "").strip(),
            callsign=(row.get("callsign") or "").strip(),
            frequencies=mhz,
            floor_ft=_level_ft(row.get("floor_fl"), 0.0),
            ceiling_ft=_level_ft(row.get("ceiling_fl"), NO_CEILING_FT),
            kind=(row.get("kind") or RADAR).strip().lower(),
            rings=(ring,), box=(min(lats), max(lats), min(lons), max(lons)),
            source=(row.get("source") or "").strip()))
    return out


@dataclass(frozen=True)
class Site:
    """A centre's remote transmitter: one frequency, the stratum it serves."""
    mhz: float
    band: str
    lat: float
    lon: float


def load_sites(path: Path) -> dict[str, list[Site]]:
    out: dict[str, list[Site]] = {}
    for row in _rows(path):
        try:
            site = Site(float(row["mhz"]), (row.get("band") or "").upper(),
                        float(row["lat"]), float(row["lon"]))
        except (KeyError, TypeError, ValueError):
            continue
        out.setdefault((row.get("artcc") or "").strip().upper(), []).append(site)
    return out


# Channels an invented frequency is drawn from: 25 kHz steps in the part of
# the band area control uses, clear of the emergency and air-to-air
# frequencies further down.
_INVENTED_LOW_MHZ = 124.0
_INVENTED_CHANNELS = 480


def invented_mhz(key: str) -> float:
    """A frequency for a sector nobody has published one for.

    Hashed from the sector, so it is the same number on every flight -- a
    pilot who wrote it down last time finds it again -- and drawn as a
    25 kHz channel so the simulator's radio can be set to it.
    """
    digest = hashlib.sha1(key.encode("utf-8")).digest()
    step = int.from_bytes(digest[:4], "big") % _INVENTED_CHANNELS
    return round(_INVENTED_LOW_MHZ + step * 0.025, 3)


