# the model

class EnRoute:
    """The sky divided into controllers' sectors, from whatever data there is."""

    # Where else to look for a sector whose frequency the pilot has tuned:
    # handed on two to four minutes before the line, the pilot dials the
    # next centre twenty or thirty miles short of it.
    LOOK_AROUND_NM = (20.0, 40.0)
    # How finely a track is walked looking for the next boundary.
    STEP_NM = 2.0

    def __init__(self, navdb: NavDB, folder: Path | None = None):
        self.navdb = navdb
        self.folder = Path(folder) if folder is not None else navdb.path.parent
        self._frequencies: dict[str, list[FrequencyRow]] | None = None
        self._pilot: list[PilotSector] | None = None
        self._faa: list[PilotSector] | None = None
        self._sites: dict[str, list[Site]] | None = None
        self._cache: dict[tuple, Sector | None] = {}
        self._named_rows: dict[str, list] = {}
        self._nearest: dict[tuple, float | None] = {}
        self._said_invented: set[str] = set()

    # ---------------------------------------------------------------- data

    @property
    def frequencies(self) -> dict[str, list[FrequencyRow]]:
        if self._frequencies is None:
            self._frequencies = load_frequencies(self.folder / FIR_FREQUENCIES)
        return self._frequencies

    @property
    def pilot_sectors(self) -> list[PilotSector]:
        if self._pilot is None:
            self._pilot = load_pilot_sectors(self.folder / PILOT_SECTORS)
        return self._pilot

    @property
    def faa_sectors(self) -> list[PilotSector]:
        if self._faa is None:
            self._faa = load_pilot_sectors(self.folder / FAA_SECTORS)
            self._sites = load_sites(self.folder / FAA_SITES)
        return self._faa

    # --------------------------------------------------------------- which

    def which(self, lat: float, lon: float, altitude_ft: float) -> Sector | None:
        """The sector containing a position at a level, or None outside all."""
        key = (round(lat, 2), round(lon, 2), int(max(0.0, altitude_ft) // 500))
        if key in self._cache:
            return self._cache[key]
        found = (self._pilot_sector(lat, lon, altitude_ft)
                 or self._vatglasses_sector(lat, lon, altitude_ft)
                 or self._faa_sector(lat, lon, altitude_ft)
                 or self._fir_sector(lat, lon, altitude_ft))
        if len(self._cache) > 20000:
            self._cache.clear()
        self._cache[key] = found
        if found is not None and found.invented:
            self._say_invented(found)
        return found

    def _pilot_sector(self, lat, lon, altitude_ft) -> Sector | None:
        s = self._containing(self.pilot_sectors, lat, lon, altitude_ft)
        if s is None:
            return None
        ident = (s.id.split("-")[0] or s.id)[:4].upper()
        return Sector(id=s.id, ident=ident, facility=s.callsign,
                      frequencies=s.frequencies, kind=s.kind, source="pilot",
                      frequency_source=s.source or PILOT_SECTORS,
                      floor_ft=s.floor_ft, ceiling_ft=s.ceiling_ft)

    def _faa_sector(self, lat, lon, altitude_ft) -> Sector | None:
        """An ARTCC from NASR, on the frequency of the site nearest.

        Every frequency of the stratum answers anywhere in it, and the one
        given in a handoff is the one transmitted nearest the point where
        the flight crosses in -- which is what a sector's frequency is, the
        sectors themselves not being published. The key does not change
        from one site to the next, so crossing an ARTCC is one controller.
        """
        s = self._containing(self.faa_sectors, lat, lon, altitude_ft)
        if s is None:
            return None
        ident = s.id.split("-")[0].upper()
        if s.ceiling_ft <= 18000.0:
            bands = {"LOW", "LOW/HIGH"}
        else:
            bands = {"HIGH", "LOW/HIGH"}
            if altitude_ft >= ULTRA_HIGH_FT:
                bands.add("ULTRA-HIGH")
        near = sorted((haversine_nm(lat, lon, site.lat, site.lon), site.mhz)
                      for site in (self._sites or {}).get(ident, [])
                      if site.band in bands)
        ordered = list(dict.fromkeys(
            [m for _, m in near if any(same_channel(m, f, 0)
                                       for f in s.frequencies)]
            + list(s.frequencies)))
        return Sector(id=s.id, ident=ident, facility=s.callsign,
                      frequencies=tuple(ordered), kind=s.kind, source="faa",
                      frequency_source=s.source or FAA_SECTORS,
                      floor_ft=s.floor_ft, ceiling_ft=s.ceiling_ft)

    @staticmethod
    def _containing(sectors, lat, lon, altitude_ft):
        """The smallest of ``sectors`` holding the point at the level.

        A ring across the 180th meridian is written with longitudes past
        180 (scripts/build_nasr.py), so the point is tried there too.
        """
        best = None
        for s in sectors:
            south, north, west, east = s.box
            if not south <= lat <= north:
                continue
            if not (s.floor_ft <= altitude_ft < s.ceiling_ft):
                continue
            if not any(west <= x <= east
                       and any(_point_in_ring(x, lat, ring) for ring in s.rings)
                       for x in (lon, lon + 360.0)):
                continue
            area = (north - south) * (east - west)
            if best is None or area < best[0]:
                best = (area, s)
        return best[1] if best else None

    def _vatglasses_sector(self, lat, lon, altitude_ft) -> Sector | None:
        station = self.navdb.sector_centre(lat, lon, altitude_ft)
        if station is None or not station.mhz:
            return None
        sector_id = (station.description or "").removeprefix("sector ").strip()
        return Sector(id=sector_id or station.facility, ident=station.ident,
                      facility=station.facility, frequencies=(station.mhz,),
                      source="vatglasses", frequency_source="VatGlasses")

    def _fir_sector(self, lat, lon, altitude_ft) -> Sector | None:
        fir = self.navdb.fir_at(lat, lon)
        if fir is None:
            return None
        fid = fir["id"]
        icao = (fir.get("icao") or fid).upper()
        ident = fid.split("-")[0][:4].upper()
        spoken = fir.get("spoken") or icao
        kind = OCEANIC if fir.get("oceanic") else RADAR

        rows = self._rows_for(fid, icao)
        here = [r for r in rows if r.floor_ft <= altitude_ft < r.ceiling_ft]
        hf = tuple(int(r.mhz) for r in here if r.kind == "hf")
        # An information service is for what is below controlled airspace
        # and is filed with no levels; ahead of a radar row for the same
        # level it would take an airliner at FL350 off Maastricht.
        vhf = sorted((r for r in here if r.kind != "hf"),
                     key=lambda r: r.kind == FIS)
        if vhf:
            first = vhf[0]
            same = tuple(r.mhz for r in vhf if r.callsign == first.callsign)
            if first.kind in (OCEANIC, FIS):
                kind = first.kind
            return Sector(id=fid, ident=ident, facility=first.callsign or spoken,
                          frequencies=same, kind=kind, source="fir",
                          frequency_source=first.source or FIR_FREQUENCIES,
                          floor_ft=first.floor_ft, ceiling_ft=first.ceiling_ft,
                          hf_khz=hf)

        return self._without_vhf(fid, ident, spoken, kind, fir, lat, lon, hf)

    def _without_vhf(self, fid, ident, spoken, kind, fir, lat, lon,
                     hf) -> Sector:
        """A FIR with no VHF row in the file: HF over the ocean, else a
        centre row borrowed from a field, else an invented frequency."""
        if kind == OCEANIC:
            # Worked on HF; a VHF number made up for it would be a radar
            # controller over the ocean, which is the one thing it is not.
            return Sector(id=fid, ident=ident, facility=f"{spoken} Radio",
                          frequencies=(), kind=OCEANIC, source="fir",
                          frequency_source="HF" if hf else "",
                          hf_khz=hf)

        icao = (fir.get("icao") or fid).upper()
        borrowed = self._borrowed(fid, fir, lat, lon)
        if borrowed:
            return Sector(id=fid, ident=ident, facility=spoken,
                          frequencies=borrowed, kind=kind, source="fir",
                          frequency_source="OurAirports centre row")

        return Sector(id=fid, ident=ident, facility=spoken,
                      frequencies=(invented_mhz(icao),), kind=kind,
                      source="fir", frequency_source="invented", invented=True)

    def _rows_for(self, fid: str, icao: str) -> list[FrequencyRow]:
        for key in (fid.upper(), fid.split("-")[0].upper(), icao):
            if key in self.frequencies:
                return self.frequencies[key]
        return []

    def _borrowed(self, fid: str, fir: dict, lat: float,
                  lon: float) -> tuple[float, ...]:
        """The centre rows filed at fields that are this FIR's, nearest first.

        Every row in and around the boundary that names the FIR, read once
        per FIR, so tuning any of them anywhere inside it is this
        controller. Only where none names it is the nearest row asked for
        (:meth:`NavDB.borrowed_centre`, with its rule against borrowing
        another country's centre) -- Amsterdam's frequency is filed as
        "Dutch" -- and that answer is kept per degree square, because the
        look-ahead asks about forty new points every ten seconds and the
        query behind it reads every centre row within 250 miles.
        """
        if fid not in self._named_rows:
            self._named_rows[fid] = self.navdb.centre_rows_named(
                fir.get("spoken") or "", fir["box"])
        named = sorted(self._named_rows[fid],
                       key=lambda r: haversine_nm(lat, lon, r[1], r[2]))
        out: list[float] = []
        if not named:
            square = (fid, round(lat), round(lon))
            if square not in self._nearest:
                found = self.navdb.borrowed_centre(lat, lon, fir)
                self._nearest[square] = found[0].mhz if found else None
            if self._nearest[square]:
                out.append(self._nearest[square])
        for station, _, _ in named:
            if not any(same_channel(station.mhz, f, 0) for f in out):
                out.append(station.mhz)
        return tuple(out)

    def _say_invented(self, sector: Sector) -> None:
        if sector.id in self._said_invented:
            return
        self._said_invented.add(sector.id)
        log.info("en-route: no frequency known for %s (%s); using %.3f, "
                 "invented", sector.facility, sector.id, sector.mhz)
        decision("enroute_frequency", sector=sector.id,
                 station=sector.station().callsign, frequency=sector.mhz,
                 source="invented")

    # ---------------------------------------------------------- next along

    def next_along(self, lat: float, lon: float, track_deg: float,
                   ground_speed_kt: float, altitude_ft: float,
                   minutes_ahead: float = 10.0,
                   route: list[tuple[float, float]] | None = None
                   ) -> Crossing | None:
        """The first different sector the flight reaches in ``minutes_ahead``.

        Along the track, or along the route when one is loaded (a SimBrief
        plan lists the waypoints, and an airway does not run straight for
        ten minutes into a corner of the next FIR it never enters).

        Without SimBrief the track alone can cross the corner of a FIR the
        flight will turn away from, and hand it there (measured near
        Singapore). Left as it is on purpose: the IFR route work is to read
        the simulator's own GPS flight plan and pass it here as ``route``,
        which fixes it for every flight without a SimBrief account.
        """
        found = self.crossings(lat, lon, track_deg, ground_speed_kt,
                               altitude_ft, minutes_ahead, route)
        return found[0] if found else None

    def crossings(self, lat: float, lon: float, track_deg: float,
                  ground_speed_kt: float, altitude_ft: float,
                  minutes_ahead: float = 10.0,
                  route: list[tuple[float, float]] | None = None
                  ) -> list[Crossing]:
        """Every change of sector along the way in ``minutes_ahead``, in order.

        The second tells how long the flight is in the first: a sector it
        is across in two minutes is one the controllers either side
        coordinate rather than hand the flight into.
        """
        current = self.which(lat, lon, altitude_ft)
        speed = max(ground_speed_kt, 1.0)
        reach = speed * minutes_ahead / 60.0
        out: list[Crossing] = []
        for run, plat, plon in self._walk(lat, lon, track_deg, reach, route):
            ahead = self.which(plat, plon, altitude_ft)
            if ahead is None or (current is not None
                                 and ahead.key == current.key):
                continue
            out.append(Crossing(ahead, run, run / speed * 60.0, plat, plon))
            current = ahead
        return out

    def _walk(self, lat, lon, track_deg, reach, route):
        legs = self._legs(lat, lon, track_deg, route)
        run = 0.0
        for (alat, alon), (blat, blon) in legs:
            length = haversine_nm(alat, alon, blat, blon)
            course = bearing_deg(alat, alon, blat, blon)
            s = self.STEP_NM
            while s <= length and run + s <= reach:
                plat, plon = project(alat, alon, course, s)
                yield run + s, plat, plon
                s += self.STEP_NM
            run += length
            if run >= reach:
                return

    @staticmethod
    def _legs(lat, lon, track_deg, route):
        far = project(lat, lon, track_deg, 2000.0)
        if not route:
            return [((lat, lon), far)]
        # The route from the first waypoint ahead of the aeroplane.
        ahead = [i for i, (plat, plon) in enumerate(route)
                 if haversine_nm(lat, lon, plat, plon) > 1.0
                 and abs((bearing_deg(lat, lon, plat, plon) - track_deg + 180)
                         % 360 - 180) < 90]
        if not ahead:
            return [((lat, lon), far)]
        points = [(lat, lon)] + list(route[ahead[0]:])
        return list(zip(points, points[1:]))

    # -------------------------------------------------------- on frequency

    def on_frequency(self, mhz: float, lat: float, lon: float,
                     altitude_ft: float, tolerance_khz: int = 4
                     ) -> Sector | None:
        """The sector here, or just ahead, that answers on this frequency."""
        seen = set()
        for plat, plon in self._around(lat, lon):
            sector = self.which(plat, plon, altitude_ft)
            if sector is None or sector.key in seen:
                continue
            seen.add(sector.key)
            if sector.answers(mhz, tolerance_khz):
                return sector
        return None

    def _around(self, lat, lon):
        yield lat, lon
        for distance in self.LOOK_AROUND_NM:
            for bearing in range(0, 360, 45):
                yield project(lat, lon, float(bearing), distance)

    # ------------------------------------------------------------- listing

    def frequencies_of(self, fir: str) -> list[FrequencyRow]:
        """The rows the shipped file has for one FIR, for ``freq <FIR>``."""
        return list(self.frequencies.get(fir.upper(), []))

    def sectors_of(self, fid: str) -> list[Sector]:
        """Every controller of one FIR, for ``freq <FIR>`` and the audit.

        The pilot's own sectors named after it, then one per callsign and
        band of levels in ``fir_frequencies.csv`` (HF together), and where
        the file has no VHF row, what a flight inside it would be worked on:
        a borrowed centre row or an invented frequency. VatGlasses sectors
        are not listed; they are drawn by position, not filed by FIR.
        """
        fir = self.navdb.fir(fid)
        if fir is None:
            return []
        fid = fir["id"]
        icao = (fir.get("icao") or fid).upper()
        ident = fid.split("-")[0][:4].upper()
        spoken = fir.get("spoken") or icao
        kind = OCEANIC if fir.get("oceanic") else RADAR
        out = [Sector(id=s.id, ident=ident, facility=s.callsign,
                      frequencies=s.frequencies, kind=s.kind, source="pilot",
                      frequency_source=s.source or PILOT_SECTORS,
                      floor_ft=s.floor_ft, ceiling_ft=s.ceiling_ft)
               for s in self.pilot_sectors
               if s.id.split("-")[0].upper() == ident]
        out += [Sector(id=s.id, ident=ident, facility=s.callsign,
                       frequencies=s.frequencies, kind=s.kind, source="faa",
                       frequency_source=s.source or FAA_SECTORS,
                       floor_ft=s.floor_ft, ceiling_ft=s.ceiling_ft)
                for s in self.faa_sectors
                if s.id.split("-")[0].upper() == ident]
        rows = self._rows_for(fid, icao)
        bands: dict[tuple, list[FrequencyRow]] = {}
        for r in rows:
            band = (r.callsign, r.floor_ft, r.ceiling_ft,
                    "hf" if r.kind == "hf" else r.kind)
            bands.setdefault(band, []).append(r)
        for (callsign, floor, ceiling, band_kind), group in bands.items():
            hf = band_kind == "hf"
            out.append(Sector(
                id=fid, ident=ident, facility=callsign or spoken,
                frequencies=() if hf else tuple(r.mhz for r in group),
                kind=OCEANIC if hf else (band_kind or kind), source="fir",
                frequency_source=group[0].source or FIR_FREQUENCIES,
                floor_ft=floor, ceiling_ft=ceiling,
                hf_khz=tuple(int(r.mhz) for r in group) if hf else ()))
        hf = tuple(int(r.mhz) for r in rows if r.kind == "hf")
        south, north, west, east = fir["box"]
        middle = ((south + north) / 2.0, (west + east) / 2.0)
        if not any(r.kind != "hf" for r in rows) and not (
                kind == OCEANIC and rows):
            out.append(self._without_vhf(fid, ident, spoken, kind, fir,
                                         *middle, hf))
        if kind != OCEANIC and fir.get("has_oceanic") and not hf:
            out.append(self._without_vhf(fid, ident, spoken, OCEANIC, fir,
                                         *middle, hf))
        return out


