"""The phrasebooks: what a controller says, in each language they say it in.

Four languages beyond English and French, chosen because they are the ones
genuinely worked on frequency alongside English in states this system has a
voice for: Spanish across Spain and Latin America, German in Germany, Austria
and German-speaking Switzerland, Italian in Italy, Portuguese in Portugal and
Brazil.

Sources are each state's own phraseology rather than a translation of the
English: AENA's Fraseología Aeronáutica, DFS's Sprechfunkverfahren, ENAV's
Fraseologia Aeronautica, and NAV Portugal / DECEA's Fraseologia. Where a
loanword is what is actually said on the radio -- "squawk" in Germany, "roger"
nowhere -- the loanword is what is written here, because the point is what a
pilot hears.

The Netherlands, Scandinavia and Poland are deliberately absent. They work
English on frequency in practice, which is what this system already does there.
"""

